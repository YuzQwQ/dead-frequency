import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
import {resolve} from 'node:path';
import {createServer} from 'vite';

if (!process.env.PLAYWRIGHT_BROWSERS_PATH && existsSync('.browser'))
  process.env.PLAYWRIGHT_BROWSERS_PATH=resolve('.browser');
const {chromium}=await import('playwright');
const vite=await createServer({server:{host:'127.0.0.1',port:0,watch:null}});
let browser;
try {
  await vite.listen();
  browser=await chromium.launch({args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
  const page=await browser.newPage({viewport:{width:1260,height:880}});
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:'+vite.httpServer.address().port+'/?qa');
  await page.evaluate(async()=>{
    const {Enemies}=await import('/src/enemies.ts');
    const {insert,stack}=await import('/src/inventory.ts');
    const update=Enemies.prototype.update;
    Enemies.prototype.update=function(dt,time,player) {
      if (!window.corpseFixture) {
        const unit=this.units.find(enemy=>enemy.kind==='scav');
        unit.kit.gear.backpack=stack('packSmall',1,true);
        insert(unit.kit.bag,stack('tape',1,true));
        unit.kit.gear.primary.rounds=7;
        unit.x=player.x-Math.sin(player.yaw)*1.75;
        unit.z=player.z-Math.cos(player.yaw)*1.75;
        player.pitch=-.60;
        player.hurt(30,'head');
        this.damage(unit,999,player);
        window.corpseFixture={weapon:unit.kit.gear.primary.key,pack:unit.kit.gear.backpack.key};
      }
      return update.call(this,dt,time,player);
    };
  });
  const click=name=>page.getByRole('button',{name,exact:true}).click();
  const menu=label=>page.locator('.ctx-row').filter({hasText:label}).click();
  await click('交易');
  for (const price of ['190','150','260']) await click('买入 · '+price+' CR');
  await click('仓库与整备');
  const preview=page.locator('[data-character-preview] canvas');
  await preview.waitFor();
  const before=await preview.screenshot();
  const previewBox=await preview.boundingBox();
  await page.mouse.move(previewBox.x+previewBox.width/2,previewBox.y+previewBox.height/2);
  await page.mouse.down();
  await page.mouse.move(previewBox.x+previewBox.width/2+38,previewBox.y+previewBox.height/2,{steps:4});
  await page.mouse.up();
  assert.notDeepEqual(await preview.screenshot(),before);
  for (const [item,slot] of [['轻型防护盔','头盔'],['巡听耳机','耳机'],['标准弹挂','弹挂']]) {
    await page.locator(`[data-grid="stash"] .cell[title="${item}"]`).click({modifiers:['Alt']});
    await page.locator(`[aria-label="${slot}"] .cell[title="${item}"]`).waitFor();
  }
  const player=page.getByRole('region',{name:'回收员',exact:true});
  assert.deepEqual(await player.locator('[data-carried]').evaluateAll(nodes=>nodes.map(node=>node.dataset.carried)),['rig','pockets','backpack']);
  const ammo=page.locator('[data-grid="stash"] .cell[title="9×19mm 弹"]');
  await ammo.click({button:'right'});
  await menu('拆分堆叠');
  await page.getByRole('spinbutton',{name:'拆出数量'}).fill('4');
  await page.getByRole('button',{name:'拆分',exact:true}).click();
  assert.equal(await ammo.count(),2);
  await ammo.last().click({modifiers:['Control']});
  assert.equal(await ammo.count(),1);
  const sidearm=player.locator('.cell[title="Glock 17"]');
  await sidearm.dblclick();
  await page.locator('dialog[open] canvas').waitFor();
  await page.keyboard.press('Escape');
  await page.locator('dialog[open]').waitFor({state:'hidden'});
  await page.getByRole('region',{name:'回收员',exact:true}).locator('.cell[title="压缩敷料"]').click({button:'right'});
  await menu('绑定 4');
  await click('行动简报');
  await page.getByRole('button',{name:'开始出击',exact:true}).click();
  await page.waitForFunction(()=>window.deadFrequencyState().hud?.prompt.includes('尸体'));
  assert.equal(await page.evaluate(()=>window.deadFrequencyState().player.hp),79);
  await page.keyboard.press('4',{delay:100});
  await page.waitForFunction(()=>window.deadFrequencyState().player.hp===100);
  await page.keyboard.press('Tab',{delay:100});
  await preview.waitFor();
  await click('状态');
  await page.getByRole('heading',{name:'行动状态'}).waitFor();
  const time=await page.locator('[data-equipment-clock]').textContent();
  await page.waitForFunction(previous=>document.querySelector('[data-equipment-clock]')?.textContent!==previous,time);
  await click('地图');
  await page.locator('.equipment-reading canvas[data-map]').waitFor();
  await page.keyboard.press('Tab',{delay:100});
  await page.waitForFunction(()=>window.deadFrequencyState().locked);
  const corpse=page.getByRole('region',{name:'拾荒者尸体',exact:true});
  const weapon=corpse.locator('.cell[title="M4A1"]');
  await page.keyboard.press('e',{delay:100});
  await corpse.waitFor();
  const fixture=await page.evaluate(()=>window.corpseFixture);
  assert.equal(await weapon.getAttribute('data-key'),fixture.weapon);
  await weapon.click();
  assert.match(await page.locator('.item-tip').textContent(),/余弹 7/);
  const backpack=corpse.locator('.cell[title="小型背包"]');
  const target=player.locator('[aria-label="背包"]');
  const from=await backpack.boundingBox(), to=await target.boundingBox();
  await page.mouse.move(from.x+20,from.y+20);
  await page.mouse.down();
  await page.mouse.move(to.x+20,to.y+20,{steps:4});
  await page.locator('.inventory-highlight.valid').waitFor();
  await page.mouse.up();
  await player.locator('.cell[title="监听磁带"]').waitFor();
  assert.equal(await player.locator('.cell[title="小型背包"]').getAttribute('data-key'),fixture.pack);
  await corpse.locator('.cell[title="旧式背包"]').waitFor();
  await player.locator('.cell[title="小型背包"]').hover();
  await page.keyboard.press('Delete');
  await page.getByRole('button',{name:'确认丢弃'}).waitFor();
  await page.keyboard.press('Escape');
  await player.locator('.cell[title="监听磁带"]').waitFor();
  await weapon.click({button:'right'});
  await menu('装备到身上');
  await player.locator('.cell[title="M4A1"]').waitFor();
  assert.equal(await weapon.count(),0);
  await page.getByRole('button',{name:'返回现场',exact:true}).click();
  await page.waitForFunction(()=>window.deadFrequencyState().locked);
  await page.waitForFunction(()=>window.deadFrequencyState().hud?.prompt.includes('查看 拾荒者尸体'));
  await page.keyboard.press('e',{delay:100});
  await corpse.waitFor();
  assert.equal(await weapon.count(),0);
  assert.equal(await corpse.locator('.cell[title="监听磁带"]').count(),0);
  assert.equal(await player.locator('.cell[title="监听磁带"]').count(),1);
  await player.locator('.cell[title="9×19mm 弹"]').first().hover();
  await page.keyboard.press('Delete');
  await page.waitForFunction(()=>window.deadFrequencyState().caches.some(cache=>cache.kind==='drop'&&cache.entries.some(item=>item.id==='9mm')));
  assert.deepEqual(errors,[]);
  console.log('Equipment browser: preview rotation, Alt equip, Ctrl transfer, stack split, details, live status clock, Delete, corpse swap and persistent looting passed.');
} finally {
  await browser?.close();
  await vite.close();
}
